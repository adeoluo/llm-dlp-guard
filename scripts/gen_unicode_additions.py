"""Write tests/unicode_additions.py: code points assigned after the Unicode version of the Rust
regex crate's tables.

Python's `re` and the Rust `regex` crate decide what a word character is (`\\w`, `\\b`) from their
own Unicode tables. The regex crate ships Unicode 16.0; Python 3.15 ships Unicode 17.0, so code
points added in 17.0 are word characters to `re` but not to the Rust core. The parity tests leave
them out, as they leave out code points that are unassigned in Python's database. Run with the
newest supported interpreter; it compares against Python 3.14 (Unicode 16.0) through uv:

    uv run --no-project --python 3.15 python scripts/gen_unicode_additions.py
"""

from __future__ import annotations

import subprocess
import sys
import unicodedata
from pathlib import Path

RUST_REGEX_UNICODE = "16.0.0"
REFERENCE_PYTHON = "3.14"
OUTPUT = Path(__file__).resolve().parent.parent / "tests" / "unicode_additions.py"

ASSIGNED = (
    "import unicodedata\n"
    "print(unicodedata.unidata_version)\n"
    "print(' '.join(str(c) for c in range(0x110000) if unicodedata.category(chr(c)) != 'Cn'))\n"
)


def assigned_here() -> set[int]:
    return {c for c in range(0x110000) if unicodedata.category(chr(c)) != "Cn"}


def assigned_in(python: str) -> tuple[str, set[int]]:
    out = subprocess.run(
        ["uv", "run", "--no-project", "--python", python, "python", "-c", ASSIGNED],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.splitlines()
    return out[0], {int(c) for c in out[1].split()}


def ranges(points: set[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for c in sorted(points):
        if out and out[-1][1] == c - 1:
            out[-1] = (out[-1][0], c)
        else:
            out.append((c, c))
    return out


def main() -> None:
    version, reference = assigned_in(REFERENCE_PYTHON)
    if version != RUST_REGEX_UNICODE:
        raise SystemExit(
            f"Python {REFERENCE_PYTHON} has Unicode {version}, not {RUST_REGEX_UNICODE}"
        )
    added = ranges(assigned_here() - reference)
    lines = [
        '"""Code points assigned after Unicode 16.0, the Rust regex crate\'s Unicode version.',
        "",
        "Generated by scripts/gen_unicode_additions.py under Unicode "
        f'{unicodedata.unidata_version}; do not edit by hand."""',
        "",
        f'RUST_REGEX_UNICODE = "{RUST_REGEX_UNICODE}"',
        f'NEWEST_UNICODE = "{unicodedata.unidata_version}"',
        "",
        "ADDED_AFTER_RUST_REGEX: tuple[tuple[int, int], ...] = (",
    ]
    lines += [f"    (0x{lo:04X}, 0x{hi:04X})," for lo, hi in added]
    lines.append(")")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    count = sum(hi - lo + 1 for lo, hi in added)
    sys.stdout.write(f"wrote {OUTPUT}: {count} code points in {len(added)} ranges\n")


if __name__ == "__main__":
    main()
